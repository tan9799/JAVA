public class xun_huan_da_yin_shu_ju {
    public static void main(String args[]) {
        int sum = 0;
        for(int i = 1; i <= 5; i++){
            sum += i;
            System.out.println(sum);
        }
        for(int i = 5; i >= 1; i--) {
            sum += i;
            System.out.println(sum);
        }
    }
}
